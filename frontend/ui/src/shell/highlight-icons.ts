// The icon a highlight leads with: its own, or a sparkle when it names none or one this
// build doesn't know, as a newer set's would be.
export const highlightIcon = (name: string | undefined): LucideIcon =>
  name !== undefined && Object.hasOwn(highlightIcons, name)
    ? highlightIcons[name as HighlightIcon]
    : Sparkles
