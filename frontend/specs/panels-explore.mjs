import { chromium } from "playwright"
const b = await chromium.launch()
const p = await b.newPage({ viewport: { width: 1280, height: 860 }, colorScheme: "light" })
await p.goto("http://127.0.0.1:5212/")
await p.waitForTimeout(4000)
await p.screenshot({ path: process.env.S + "/home.png" })
const dbg = p.getByRole("button", { name: /debug panel/i })
console.log("dbg count", await dbg.count())
await dbg.first().click()
await p.waitForTimeout(800)
await p.screenshot({ path: process.env.S + "/debug.png" })
const txt = await p.evaluate(() => [...document.querySelectorAll("button, summary, h2, h3")].map(e => e.tagName + ":" + (e.getAttribute("aria-label")||e.textContent.trim()).slice(0,60)).join("\n"))
console.log(txt)
await b.close()
