// What gets the person back into an agent's task at a glance: the last words it was given,
// by the person or by its lead, and the few steps it took since that edited, ran or failed,
// each with what came of it. Read from its transcript as its harness's decoder gave it, the
// same for Claude Code, Codex and Antigravity. Pure: the Inbox's sheet shows what this returns.

// One step: a tool call that edited, ran or failed, in the harness's own words. `tool` is
// the tool's name as the harness gave it ("Edit", "exec_command", "edit_file"); `arg` what
// it was called on, on one line; `result` what came of it: "+4 −2" for an edit, a short line
// for a run, the error for a failure, or null where nothing says.
export type AgentStep = {
  readonly kind: "edit" | "run" | "fail"
  readonly tool: string
  readonly arg: string
  readonly result: string | null
}

// Words the agent was given: `by` null for the person, a lead's bare handle for a handoff.
export type Said = { readonly text: string; readonly by: string | null; readonly at: number }

export type AgentContext = {
  readonly said: Said | null
  // At most `maxSteps`, oldest first.
  readonly steps: readonly AgentStep[]
}

export const maxSteps = 3

// Words shorter than this ("ok", "go on") say nothing of the task: the words before them do.
const fillerWords = 3

// The longest a step's result runs before it's cut.
const maxResult = 80

// Lines Novadeck types into the agent for itself: its doorbell, and what hooks give back as
// a prompt (Codex's `<hook_prompt>`, a delivery of agents' messages). Never the person's.
const doorbell = /\[Novadeck: automatic notice, agent messages waiting, [A-Za-z0-9]+\]/g
const continuation = (text: string): boolean =>
  /^\s*<hook_prompt\b/.test(text) || text.includes("<novadeck-messages")

// What Novadeck sends the agent for the person when they ask it to fix a failed turn.
export const askToFixNudge = "Your last turn ended in an error. Look at what went wrong and fix it."

// A slash command Claude Code writes down as plain user records: the command
// (`<command-name>`, `<command-message>`, `<command-args>`), what it printed
// (`<local-command-stdout>`, `-stderr`) and the caveat before them. Codex and Antigravity
// run theirs in the terminal UI and record nothing of them as a prompt.
const slashCommand = (text: string): boolean =>
  /^\s*<(command-name|command-message|command-args|local-command-(stdout|stderr|caveat))>/.test(
    text,
  ) ||
  /^\s*Caveat: The messages below were generated by the user while running local commands/.test(
    text,
  )

// The person's words in a user item, without a doorbell line left in it; null for an item
// that holds none: a stop, a hook's continuation, or a command run in the agent's shell
// mode (`!command`, which both Claude Code and Codex record so).
const personWords = (item: ChatItem, notices: readonly string[]): string | null => {
  if (item.role !== "user" || item.kind !== "text" || item.interrupted) return null
  if (continuation(item.text) || slashCommand(item.text)) return null
  const text = item.text.replace(doorbell, "").trim()
  if (!text || text.startsWith("!") || notices.includes(text)) return null
  return text
}

const words = (text: string): number => text.split(/\s+/).filter(Boolean).length

// Where the said words came from: an item of the transcript, by index, or a message
// delivered to the agent at a time.
type Spoken = Said & { readonly index: number | null }

// The latest that says something, else the latest at all.
const latest = (spoken: readonly Spoken[]): Spoken | undefined => {
  const ordered = spoken.toSorted((a, b) => a.at - b.at)
  return ordered.findLast((each) => words(each.text) >= fillerWords) ?? ordered.at(-1)
}

// When each item was written: its own time, or the time of the last item before it that has
// one, as an item with none came after it.
const timesOf = (items: readonly ChatItem[]): readonly number[] => {
  let last = 0
  return items.map((item) => (last = item.at ?? last))
}

// The first item after the words: the next one after the person's turn, or, for a message,
// the first written since it came.
const startOf = (chosen: Spoken | undefined, times: readonly number[]): number => {
  if (chosen === undefined) return 0
  if (chosen.index !== null) return chosen.index + 1
  const index = times.findIndex((time) => time >= chosen.at)
  return index === -1 ? times.length : index
}

/**
 * An agent's context from its transcript's items, by its harness's name for it (`claude`,
 * `codex`, `agy`, as `Conversation.agent` gives it), and the messages delivered to it that
 * count as its words (`handoffs`: its lead's, and the person's replies from the Inbox): the
 * latest words, skipping filler for the words before it, and the last `maxSteps` steps after
 * them that edited, ran or failed and have a result. With no words, the last steps at all.
 */
export const agentContext = (
  agent: string | null,
  items: readonly ChatItem[],
  handoffs: readonly Said[] = [],
  // Lines Novadeck sent the agent for itself, which come back as user items but aren't the
  // person's words: the stuck nudge a Nudge sends (`trouble.nudge`, which comes from data).
  notices: readonly string[] = [],
): AgentContext => {
  const times = timesOf(items)
  const skipped = [askToFixNudge, ...notices]
  const turns = items.flatMap((item, index): Spoken[] => {
    const text = personWords(item, skipped)
    return text === null ? [] : [{ text, by: null, at: times[index]!, index }]
  })
  const chosen = latest([...turns, ...handoffs.map((each) => ({ ...each, index: null }))])
  const entries = groupItems(items.slice(startOf(chosen, times))).flatMap((block) =>
    block.kind === "tools" ? block.entries : [],
  )
  // From the end, and no further than the steps that are wanted: a step costs its input's
  // parse and diff, which a long transcript's older calls need not pay.
  const steps: AgentStep[] = []
  for (let index = entries.length - 1; index >= 0 && steps.length < maxSteps; index -= 1) {
    const step = stepOf(agent, entries, index)
    if (step) steps.unshift(step)
  }
  return {
    said: chosen ? { text: chosen.text, by: chosen.by, at: chosen.at } : null,
    steps,
  }
}

// The messages delivered to a terminal's agent that count as words it was given, when it
// got them: its lead's (`lead`, the handle of the terminal that opened it with a brief), and
// the person's replies from the Inbox, which Novadeck delivers as messages too. Its harness's
// transcript doesn't hold them as the person's: Claude Code and Antigravity get them as a
// hook's context, Codex as a developer message, its prompt only Novadeck's doorbell line.
export const handoffsOf = (
  threads: TerminalThreads | undefined,
  lead: string | null,
): readonly Said[] =>
  (threads?.threads ?? []).flatMap((thread) =>
    thread.messages.flatMap((message): Said[] => {
      if (message.to !== threads!.handle || message.deliveredAt === null) return []
      const text = message.text.trim()
      if (!text) return []
      if (message.inbox === "answer") return [{ text, by: null, at: message.deliveredAt }]
      if (message.inbox || lead === null || message.from !== lead) return []
      return [{ text, by: lead, at: message.deliveredAt }]
    }),
  )

// The lead of the terminal at `key`, whose messages count as words its agent was given:
// the terminal that opened it with a brief, as its backend last said, or, once that ended,
// the one that opened it; null where the person opened it or it's gone.
export const leadOf = (workspace: Workspace, key: CompanionKey): string | null => {
  const terminal = workspace.projects
    .find((project) => project.id === key.projectId)
    ?.history.find((session) => session.id === key.workspaceSessionId)
    ?.state.roster.terminals.find((each) => each.id === key.terminalId)
  return terminal?.ledBy || terminal?.openedBy || null
}

// ---- Steps ----

// A call the person turned down, or stopped, rather than one that ran: Claude Code's
// rejection and its auto mode's, Codex's rejected or aborted call, Antigravity's denied one.
const declined =
  /^(The user doesn't want to proceed with this tool use|Permission for this action was denied)|Rejected\(|\baborted by user\b|\btool call denied\b|\brejected by (the )?user\b/

// A step from a tool call with its result: a failure whatever the tool, else an edit or a
// run; null for any other call, one still running (as the one the person is asked about),
// or one the person declined.
const stepOf = (
  agent: string | null,
  entries: readonly ToolEntry[],
  index: number,
): AgentStep | null => {
  const entry = entries[index]!
  const { tool, run, input, result } = entry
  if (!tool || !run || !result) return null
  const output = clean(result.text)
  if (declined.test(output)) return null
  if (tool === "write_stdin") return pollStep(agent, entries, index, output)
  // A command still running when it was called, whose later polls tell how it ended.
  const session = runningSession(output)
  if (session !== undefined && entries.slice(index + 1).some((each) => ended(each, session)))
    return null
  const patch = patchOf(tool, input)
  const kind = patch !== undefined ? "write" : run.kind
  const arg =
    patch !== undefined && patch.files.length > 0
      ? fileArg(patch.files)
      : tool === "exec"
        ? (scriptCommand(input) ?? run.detail)
        : run.detail
  const failure = failureOf(agent, tool, output)
  if (failure !== undefined) return { kind: "fail", tool, arg, result: failure }
  if (kind === "write")
    return { kind: "edit", tool, arg, result: counted(patch?.counts ?? editCounts(tool, input)) }
  if (kind === "run") return { kind: "run", tool, arg, result: lastLine(output) }
  return null
}

// ---- Polls ----

// Codex's long commands answer `Process running with session ID N` and are polled with
// `write_stdin`: an empty `chars` waits for more output, and the result that says how the
// command ended is the last poll's.
const runningSession = (output: string): string | undefined =>
  /^Process running with session ID (\d+)/m.exec(head(output))?.[1]

const polled = (entry: ToolEntry): string | undefined => {
  if (entry.tool !== "write_stdin") return undefined
  const fields = fieldsOf(entry.input)
  const chars = fields?.chars
  if (typeof chars === "string" && chars !== "") return undefined
  const id = fields?.session_id
  return typeof id === "number" || typeof id === "string" ? String(id) : undefined
}

// Whether `entry` is a poll of `session` that found the command ended.
const ended = (entry: ToolEntry, session: string): boolean =>
  polled(entry) === session &&
  entry.result !== null &&
  runningSession(clean(entry.result.text)) === undefined

// The step a poll gives: none where the command still runs, else the command's own, as it
// ended. Input typed into a command (`chars`) is a step of its own, as any other run.
const pollStep = (
  agent: string | null,
  entries: readonly ToolEntry[],
  index: number,
  output: string,
): AgentStep | null => {
  const entry = entries[index]!
  const session = polled(entry)
  if (session === undefined) {
    const failure = failureOf(agent, "write_stdin", output)
    const arg = entry.run!.detail
    if (failure !== undefined) return { kind: "fail", tool: "write_stdin", arg, result: failure }
    return { kind: "run", tool: "write_stdin", arg, result: lastLine(output) }
  }
  if (runningSession(output) !== undefined) return null
  const started = entries
    .slice(0, index)
    .findLast(
      (each) =>
        each.tool !== "write_stdin" &&
        each.result &&
        runningSession(clean(each.result.text)) === session,
    )
  const tool = started?.tool ?? "write_stdin"
  const arg = started
    ? tool === "exec"
      ? (scriptCommand(started.input) ?? started.run!.detail)
      : started.run!.detail
    : `session ${session}`
  const failure = failureOf(agent, tool, output)
  if (failure !== undefined) return { kind: "fail", tool, arg, result: failure }
  return { kind: "run", tool, arg, result: lastLine(output) }
}

// The command a Codex code-mode script runs (`tools.exec_command({cmd: "…"})`), its first
// line, and how many more it runs; undefined for a script that runs none.
const scriptCommand = (script: string): string | undefined => {
  const commands = [
    ...script.matchAll(/tools\.exec_command\(\{\s*"?cmd"?\s*:\s*"((?:[^"\\]|\\.)*)"/g),
  ].map((match) => unescape(match[1]!).trim().split("\n", 1)[0]!)
  if (commands.length === 0) return undefined
  return commands.length === 1 ? commands[0] : `${commands[0]} +${commands.length - 1}`
}

// ---- Failures ----

// Terminal colours, which a run's output may carry.
// eslint-disable-next-line no-control-regex -- The escape is what it matches.
const ansi = /\x1b\[[0-9;?]*[A-Za-z]/g

const clean = (text: string): string => text.replace(ansi, "").replace(/\r/g, "")

const lines = (text: string): string[] =>
  text
    .split("\n")
    .map((line) => line.trim())
    .filter(Boolean)

const cut = (line: string): string =>
  line.length > maxResult ? `${line.slice(0, maxResult - 1).trimEnd()}…` : line

// The lines of a result before its output: where Codex and Antigravity say how a run ended.
const head = (text: string): string => text.split(/\nOutput:\n|\nStdout:\n/, 1)[0]!

// What a run printed, without what its harness wrote around it.
const printed = (text: string): string => {
  const output = /\nOutput:\n([\s\S]*)$/.exec(text)?.[1] ?? text
  return lines(output).map(chunkOutput).join("\n")
}

// A Codex code-mode chunk (`{"chunk_id": …, "output": "…"}`) as the output it holds.
const chunkOutput = (line: string): string => {
  if (!line.startsWith("{")) return line
  try {
    const value = JSON.parse(line) as { output?: unknown }
    return typeof value.output === "string" ? value.output.trim() : ""
  } catch {
    return line
  }
}

// The lines a harness writes about a run, not by it.
const about =
  /^(Created At|Completed At): |^(The )?[Cc]ommand exited with code -?\d+\.?$|^(Stdout|Stderr):$|^No output from the command\.$|^(Chunk ID|Wall time|Original token count): |^Wall time [\d.]+ seconds$|^Process exited with code -?\d+$|^Exit code:? -?\d+$|^Script (completed|failed)$|^Output:$|^\[exit code -?\d+\]$|^\{\}$/

// The last line a run printed, cut short; null where it printed nothing.
const lastLine = (text: string): string | null => {
  const last = lines(printed(text)).findLast((line) => !about.test(line))
  return last === undefined ? null : cut(last)
}

// A line, cut short, or undefined for none.
const said = (line: string | undefined): string | undefined =>
  line === undefined ? undefined : cut(line)

// Why a call failed, as its harness's result says, or undefined where it didn't (or the
// harness doesn't say). No decoder carries a flag, so each harness's own words tell:
// - Claude Code: a failed command's result starts `Exit code N`, or `Command timed out
//   after …`; a tool's own error is wrapped in `<tool_use_error>`.
// - Codex: `Process exited with code N` (exec_command), `Exit code: N` then `Wall time:`
//   (its shell and patch tools' header), a shell's older JSON output with
//   `"metadata":{"exit_code":N}`, `[exit code N]` (a shell-mode command, as the decoder writes it),
//   `apply_patch verification failed`, and in code mode `Script failed` with its
//   `Script error:`, or a chunk's `"exit_code": N`.
// - Antigravity: a step that errored reads `Encountered error in step execution: …`, and a
//   command `Command exited with code N.`.
// The failure reads as the error's own line, else the last line printed, else the exit code.
export const failureOf = (agent: string | null, tool: string, text: string): string | undefined => {
  const output = clean(text)
  const exited = (code: string): string => lastLine(output) ?? `exit code ${code}`
  if (agent === "claude") {
    const error = /^<tool_use_error>([\s\S]*?)(<\/tool_use_error>|$)/.exec(output)
    if (error) return said(lines(error[1]!)[0] ?? "failed")
    if (output.startsWith("Command timed out after ")) return said(lines(output)[0])
    const code = /^Exit code (-?\d+)/.exec(output)?.[1]
    if (code && code !== "0") return said(lines(output).slice(1).at(-1)) ?? `exit code ${code}`
    return undefined
  }
  if (agent === "codex") {
    const scriptError = /\nScript error:\n([\s\S]*)$/.exec(output)?.[1]
    if (/^Script failed\b/.test(output))
      return said(scriptError ? lines(scriptError)[0] : undefined) ?? exited("1")
    const header = head(output)
    const code =
      /^Process exited with code (-?\d+)$/m.exec(header)?.[1] ??
      // Its shell's header, which a patch run through exec_command nests after its own.
      /^Exit code: (-?\d+)\nWall time:/m.exec(output)?.[1] ??
      /\[exit code (-?\d+)\]$/.exec(output)?.[1] ??
      /"metadata":\s*\{[^{}]*"exit_code":\s*(-?\d+)/.exec(output)?.[1] ??
      (tool === "exec" ? /"exit_code":\s*(-?[1-9]\d*)/.exec(output)?.[1] : undefined)
    // A run that exited 0 succeeded, whatever it printed: a log it cat'ed may hold the words.
    if (code === "0") return undefined
    const patch = /^apply_patch verification failed:?.*$/m.exec(output)?.[0]
    if (patch) return said(patch)
    if (code) return exited(code)
    return undefined
  }
  if (agent === "agy") {
    const code = /^(?:The )?[Cc]ommand exited with code (-?\d+)\.?$/m.exec(head(output))?.[1]
    // As with Codex: exited 0 is a success, even if the output prints the error's words.
    if (code === "0") return undefined
    const error = /^Encountered error in step execution: (.*)$/m.exec(output)?.[1]
    if (error !== undefined) return said(error) ?? "failed"
    if (code) return exited(code)
    return undefined
  }
  return undefined
}

// ---- Edits ----

type Counts = { readonly added: number; readonly removed: number }

const counted = (counts: Counts | null): string | null => {
  if (!counts || (counts.added === 0 && counts.removed === 0)) return null
  return [counts.added > 0 && `+${counts.added}`, counts.removed > 0 && `−${counts.removed}`]
    .filter(Boolean)
    .join(" ")
}

// A text's lines, a final newline ending the last rather than starting another.
const textLines = (text: string): string[] =>
  text === "" ? [] : text.replace(/\n$/, "").split("\n")

// The longest the lines left after trimming what two texts share at either end may be,
// multiplied, before they're counted whole rather than matched line by line.
const maxMatch = 250_000

// How many lines an edit from `before` to `after` adds and removes: what the two share at
// either end left out, and the lines of the rest they have in common (their longest common
// subsequence), where it's small enough to match.
export const lineCounts = (before: string, after: string): Counts => {
  const old = textLines(before)
  const next = textLines(after)
  let start = 0
  while (start < old.length && start < next.length && old[start] === next[start]) start += 1
  let end = 0
  while (
    end < old.length - start &&
    end < next.length - start &&
    old[old.length - 1 - end] === next[next.length - 1 - end]
  )
    end += 1
  const a = old.slice(start, old.length - end)
  const b = next.slice(start, next.length - end)
  const common = a.length * b.length <= maxMatch ? shared(a, b) : 0
  return { added: b.length - common, removed: a.length - common }
}

// The length of the longest common subsequence of two lists of lines.
const shared = (a: readonly string[], b: readonly string[]): number => {
  let row: number[] = Array.from({ length: b.length + 1 }, () => 0)
  for (const line of a) {
    const next = [0]
    for (let j = 0; j < b.length; j += 1)
      next.push(line === b[j] ? row[j]! + 1 : Math.max(row[j + 1]!, next[j]!))
    row = next
  }
  return row[b.length]!
}

const sum = (all: readonly Counts[]): Counts => ({
  added: all.reduce((total, each) => total + each.added, 0),
  removed: all.reduce((total, each) => total + each.removed, 0),
})

type Fields = Readonly<Record<string, unknown>>

const fieldsOf = (input: string): Fields | null => {
  try {
    const value: unknown = JSON.parse(input)
    return typeof value === "object" && value !== null && !Array.isArray(value)
      ? (value as Fields)
      : null
  } catch {
    return null
  }
}

// A string argument, with the JSON quoting Antigravity may wrap it in a second time undone.
const textOf = (value: unknown): string | undefined => {
  if (typeof value !== "string") return undefined
  if (value.length >= 2 && value.startsWith('"') && value.endsWith('"'))
    try {
      const inner: unknown = JSON.parse(value)
      if (typeof inner === "string") return inner
    } catch {
      // Not quoted after all.
    }
  return value
}

const firstText = (fields: Fields | null, ...keys: string[]): string | undefined => {
  for (const key of keys) {
    const text = textOf(fields?.[key])
    if (text !== undefined) return text
  }
  return undefined
}

// A list argument, as given or as the JSON text Antigravity may wrap it in.
const listOf = (value: unknown): readonly Fields[] => {
  const parsed: unknown =
    typeof value === "string"
      ? (() => {
          try {
            return JSON.parse(textOf(value) ?? value) as unknown
          } catch {
            return undefined
          }
        })()
      : value
  return Array.isArray(parsed)
    ? parsed.filter((each): each is Fields => typeof each === "object" && each !== null)
    : []
}

// What a replacement takes out and puts in: Claude Code's `old_string`/`new_string`,
// Antigravity's `Target`/`Replacement` (1.4) or `TargetContent`/`ReplacementContent`.
const replaced = (fields: Fields | null): Counts | null => {
  const before = firstText(fields, "old_string", "Target", "TargetContent")
  const after = firstText(fields, "new_string", "Replacement", "ReplacementContent")
  return before === undefined || after === undefined ? null : lineCounts(before, after)
}

// What an edit tool's call adds and removes, from its input: Claude Code's Edit, MultiEdit
// and Write, Antigravity's edit_file and write_file (1.4), and replace_file_content,
// multi_replace_file_content and write_to_file before. A whole file written counts its
// lines as added. Null where the input doesn't say.
export const editCounts = (tool: string, input: string): Counts | null => {
  const fields = fieldsOf(input)
  if (!fields) return null
  const edits = listOf(fields.edits ?? fields.ReplacementChunks)
  if (edits.length > 0) {
    const all = edits.map(replaced)
    return all.every((each) => each !== null) ? sum(all) : null
  }
  const one = replaced(fields)
  if (one) return one
  const written = firstText(fields, "content", "Content", "CodeContent")
  if (written !== undefined && /write/i.test(tool))
    return { added: textLines(written).length, removed: 0 }
  return null
}

// ---- Patches ----

// A Codex patch a call applies: the files it names and the lines it adds and removes. The
// apply_patch tool takes it raw or as JSON; a shell may run it (`apply_patch <<'EOF'`), and
// code mode's `exec` within a script (`tools.apply_patch("…")`), its newlines escaped.
type Patch = { readonly files: readonly string[]; readonly counts: Counts }

const patchBody = /\*\*\* Begin Patch([\s\S]*?)\*\*\* End Patch/g

const patchOf = (tool: string, input: string): Patch | undefined => {
  if (!input.includes("*** Begin Patch")) return undefined
  // A code-mode script that does more than apply patches ran, rather than edited.
  if (tool === "exec" && /\btools\.(?!apply_patch\b)\w+\(/.test(input)) return undefined
  const fields = fieldsOf(input)
  const text = firstText(fields, "input", "patch", "cmd", "command") ?? input
  const bodies = [...text.matchAll(patchBody)].map((match) =>
    tool === "exec" || !match[1]!.includes("\n") ? unescape(match[1]!) : match[1]!,
  )
  if (bodies.length === 0) return undefined
  const files = new Set<string>()
  let added = 0
  let removed = 0
  for (const body of bodies)
    for (const line of body.split("\n")) {
      const file = /^\*\*\* (?:Add|Update|Delete) File: (.+?)\s*$/.exec(line)?.[1]
      if (file) files.add(file)
      else if (line.startsWith("*** ")) continue
      else if (line.startsWith("+")) added += 1
      else if (line.startsWith("-")) removed += 1
    }
  return { files: [...files], counts: { added, removed } }
}

// A patch as a script's string literal holds it, its escapes undone.
const unescape = (literal: string): string =>
  literal.replace(/\\(.)/g, (_, char: string) => (char === "n" ? "\n" : char === "t" ? "\t" : char))

// Files on one line, as the harnesses' own lines name them: each path's last three parts,
// the first two files and how many more.
const shortPath = (path: string): string => {
  const parts = path.split(/[\\/]+/).filter(Boolean)
  return parts.length > 3 ? `…/${parts.slice(-3).join("/")}` : path
}

const fileArg = (files: readonly string[]): string =>
  files.length <= 2
    ? files.map(shortPath).join(", ")
    : `${files.slice(0, 2).map(shortPath).join(", ")} +${files.length - 2}`
