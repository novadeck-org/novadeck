const trailerKeys = [
  "co-authored-by",
  "generated-by",
  "assisted-by",
  "created-by",
  "authored-by",
  "written-by",
  "co-developed-by",
  "ai-assisted-by",
]

// "Generated with Codex", "🤖 Generated with [Claude Code](...)", "Co-authored with Gemini".
// The tool must be the object, so prose such as "Generated by pnpm from Codex's schema" passes.
const generated = /^[^\p{L}\p{N}]*(?:generated|co-authored)\s+(?:with|by|using)\s*:?\s+(.*)$/iu
const trailer = new RegExp(`^(?:${trailerKeys.join("|")})\\s*:\\s*(.*)$`, "i")

export type Attribution = { line: string; tool: string }

const toolIn = (text: string, atStart = false): string | undefined =>
  aiTools.find((tool) => {
    const match = tool.pattern.exec(text)
    return match !== null && (!atStart || match.index === 0)
  })?.name

const htmlTag =
  /<\/?(?:sub|sup|b|i|em|strong|small|p|br|a|span|div|center|code|details|summary)(?=[\s/>])[^>]*>/gi

export const findAttributions = (text: string): Attribution[] => {
  const found: Attribution[] = []
  for (const raw of text.split(/\r?\n/)) {
    const line = raw
      .replace(htmlTag, "")
      .replace(/^[\s>*-]+/, "")
      .trim()
    const named = trailer.exec(line)?.[1]
    const object = generated.exec(line)?.[1]
    const tool =
      named !== undefined
        ? toolIn(named)
        : object === undefined
          ? undefined
          : toolIn(object.replace(/^[^\p{L}\p{N}]+/u, ""), true)
    const footer = aiTools.find((candidate) => candidate.footer?.test(raw))?.name
    if (tool ?? footer) found.push({ line: raw.trim(), tool: tool ?? footer ?? "" })
  }
  return found
}

export type Source = { label: string; text: string }

export const attributionErrors = (sources: Source[]): string[] =>
  sources.flatMap(({ label, text }) =>
    findAttributions(text).map(({ line, tool }) => {
      const fix = label.startsWith("Commit")
        ? "Reword the commit and push it, or open a new branch with the reworded commits."
        : "Delete that line."
      return `${label} has AI attribution (${tool}): "${line}". ${fix}`
    }),
  )
