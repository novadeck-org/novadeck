import { context, describe, expect, it } from "../../test"
import { attributionErrors, findAttributions } from "./attribution"

describe("AI attribution", () => {
  context("when a Co-authored-by trailer names an AI tool", () => {
    it.each([
      "Co-authored-by: Claude <noreply@anthropic.com>",
      "Co-Authored-By: Claude Opus 4.7 <noreply@anthropic.com>",
      "Co-authored-by: Codex <codex@openai.com>",
      "co-authored-by: ChatGPT <noreply@openai.com>",
      "Co-authored-by: Antigravity <noreply@google.com>",
      "Co-authored-by: Gemini <gemini@google.com>",
      "Co-authored-by: Jules <jules@google.com>",
      "Co-authored-by: Copilot <175728472+Copilot@users.noreply.github.com>",
      "Co-authored-by: cursoragent <cursoragent@cursor.com>",
      "Co-authored-by: aider (gpt-4o) <noreply@aider.chat>",
      "Co-authored-by: devin-ai-integration[bot] <158243242+devin-ai-integration[bot]@users.noreply.github.com>",
      "Co-authored-by: Windsurf <cascade@windsurf.com>",
      "Co-authored-by: Amazon Q <noreply@amazon.com>",
    ])("flags %s", (line) => {
      expect(findAttributions(`feat: x\n\n${line}\n`)).toHaveLength(1)
    })
  })

  context("when another attribution trailer or Generated line names an AI tool", () => {
    it.each([
      "Generated-by: Claude Code",
      "Assisted-by: Codex",
      "Assisted-by: Antigravity",
      "🤖 Generated with [Claude Code](https://claude.com/claude-code)",
      "Generated with Codex",
      "Generated with Codex CLI",
      "Generated with [Antigravity](https://antigravity.google)",
      "Generated by Gemini CLI",
      "> Generated with GitHub Copilot",
      "Generated using Cursor",
      "Generated with: Claude Code",
      "<sub>🤖 Generated with [Claude Code](https://claude.com/claude-code)</sub>",
      "Co-developed-by: Codex <codex@openai.com>",
      "AI-assisted-by: Gemini",
      "Co-authored-by: Amp <amp@ampcode.com>",
      "Co-authored-by: Warp <agent@warp.dev>",
      "Co-authored-by: Crush <crush@charm.land>",
      "Co-authored-by: OpenHands <openhands@all-hands.dev>",
      "Co-authored-by: factory-droid[bot] <138933559+factory-droid[bot]@users.noreply.github.com>",
      "Co-authored-by: Mistral Vibe <vibe@mistral.ai>",
      "Co-authored-by: Qwen-Coder <qwen-coder@alibabacloud.com>",
      "Co-authored-by: Kiro <kiro@amazon.com>",
      '<a href="https://jules.google.com/task/1">x</a>',
      "Co-authored-by: Bot <a+bot@anthropic.com>",
      "Co-authored-by: Bot <p.bot@openai.com>",
      "Task: https://chatgpt.com/codex/tasks/task_e_123",
      "[View Jules task](https://jules.google.com/task/123)",
      "PR created automatically by Jules for task 123 started by @someone",
      "Session: https://app.devin.ai/sessions/abc",
      "Co-authored with Gemini",
    ])("flags %s", (line) => {
      expect(findAttributions(`## What\nDone\n\n${line}`)).toHaveLength(1)
    })
  })

  context("when the text only mentions a tool or credits a person", () => {
    it.each([
      "Co-authored-by: dependabot[bot] <49699333+dependabot[bot]@users.noreply.github.com>",
      "Co-authored-by: Jules Verne <jules@example.com>",
      "Co-authored-by: Devin Smith <devin@example.com>",
      "Co-authored-by: Mateusz <mateusz@mzpk.dev>",
      "Signed-off-by: Mateusz <mateusz@mzpk.dev>",
      "Signed-off-by: Claude <noreply@anthropic.com>",
      "Generated with the TypeScript compiler",
      "Generated by `pnpm` from Codex's schema",
      "See https://claude.com/claude-code for the product page",
      "Generated by pnpm from Codex's schema",
      "- Created by `open_agent` with Codex",
      "Written by the agent when Claude Code's hook fires",
      "The schema is generated by the runner",
      "Codex's ask reaches the Inbox",
      "Claude Code and Antigravity share the Stop hook",
      "Release notes: thanks @Copilot for the fix",
    ])("passes %s", (line) => {
      expect(findAttributions(line)).toEqual([])
    })
  })

  it("flags a line in CRLF text", () => {
    expect(
      findAttributions("fix: x\r\n\r\nCo-authored-by: Claude <noreply@anthropic.com>\r\n"),
    ).toHaveLength(1)
  })

  it("names the source and the offending line", () => {
    expect(
      attributionErrors([
        { label: "The pull request description", text: "## What\nok" },
        {
          label: "Commit abc1234",
          text: "fix: x\n\nCo-authored-by: Claude <noreply@anthropic.com>",
        },
      ]),
    ).toEqual([
      expect.stringMatching(/^Commit abc1234 has AI attribution .*Co-authored-by: Claude/),
    ])
  })
})
