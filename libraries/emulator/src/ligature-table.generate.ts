import { writeFileSync } from "node:fs"

import { loadShaper, type Shaper } from "./ligature-font.test-kit.ts"

// Writes `ligature-table.ts` from the bundled JetBrains Mono: `node src/ligature-table.generate.ts`
// (about three minutes). Every string up to four glyphs over the glyphs that take part in any
// ligature is asked of the font's rules; a string the font draws wholly as one ligature joins
// the table unless the table's shorter sequences already cover it.

const printable = Array.from({ length: 95 }, (_, i) => String.fromCharCode(32 + i))

const joins = (text: string, shape: Shaper): boolean[] => {
  const marks = Array.from({ length: text.length }, () => false)
  for (const [from, to] of shape(text)) for (let i = from; i < to; i++) marks[i] = true
  return marks
}

// The glyphs that join with a neighbour in some pair, and in some triple of such glyphs and
// any other.
const alphabetOf = (shape: Shaper): string[] => {
  const found = new Set<string>()
  const note = (text: string): void => {
    joins(text, shape).forEach((on, i) => on && found.add(text[i] ?? ""))
  }
  for (const a of printable) for (const b of printable) note(a + b)
  const pairs = [...found]
  for (const a of printable)
    for (const b of pairs)
      for (const c of pairs) for (const text of [a + b + c, b + a + c, b + c + a]) note(text)
  return [...found].toSorted()
}

const covers = (text: string, sequences: readonly string[]): boolean => {
  const marks = Array.from({ length: text.length }, () => false)
  for (let at = 0; at < text.length; at++)
    for (const sequence of sequences)
      if (text.startsWith(sequence, at))
        for (let i = at; i < at + sequence.length; i++) marks[i] = true
  return marks.every(Boolean)
}

const strings = function* (alphabet: readonly string[], length: number): Generator<string> {
  const at = Array.from({ length }, () => 0)
  for (;;) {
    yield at.map((i) => alphabet[i]).join("")
    let place = length - 1
    while (place >= 0 && ++at[place]! === alphabet.length) at[place--] = 0
    if (place < 0) return
  }
}

const shape = await loadShaper()
const alphabet = alphabetOf(shape)
const sequences: string[] = []
for (let length = 2; length <= 4; length++)
  for (const text of strings(alphabet, length)) {
    const ranges = shape(text)
    const whole = ranges.length === 1 && ranges[0]?.[0] === 0 && ranges[0][1] === length
    if (whole && !covers(text, sequences)) sequences.push(text)
  }

writeFileSync(
  new URL("./ligature-table.ts", import.meta.url),
  `// Generated by \`node src/ligature-table.generate.ts\` from the bundled JetBrains Mono
// (@fontsource-variable/jetbrains-mono): the sequences its ligature rules join, up to four
// glyphs, shorter ones first. Longer runs are these, overlapping. Do not edit by hand;
// \`ligature-font.test.ts\` fails when the font and this table disagree.
export const ligatureSequences: readonly string[] = ${JSON.stringify(sequences, null, 2)}
`,
)
console.log(`${sequences.length} sequences over ${alphabet.join("")}`)
